#!/usr/bin/env python3
"""gen-walk-step.py <seedtree.c> <out.c> : compositional (1-induction) proof obligations for the two seed-tree walks.

Extracts, VERBATIM, the inner-loop body of RebuildGGM and of CountPublishedSeeds from the real seedtree.c and wraps each in a
step function that (1) starts from an ARBITRARY state satisfying the loop invariant, (2) executes ONE iteration of the real body,
(3) computes the real loop successor, (4) asserts the invariant again (or the exit condition). Invariant (both walks):
    1 <= level <= LOG2(T),  0 <= node_in_level < npl[level],  start_node == P[level],
    used == S[1] - S[start_node + node_in_level]
where S[j] = number of nodes k >= j (in walk order) that satisfy  F[k]==TO_PUBLISH && F[father(k)]==NOT_TO_PUBLISH  (ghost).
Because every iteration is checked from every invariant state, the result covers ALL iterations of the walk without unrolling it."""
import re, sys
src = open(sys.argv[1]).read()
def inner_body(fn_sig, counter):
    i = src.index(fn_sig)
    hdr = 'for (int node_in_level = 0; node_in_level < npl[level]; node_in_level++'
    j = src.index(hdr, i); j = src.index('{', j) + 1
    depth, k = 1, j
    while depth:
        depth += {'{': 1, '}': -1}.get(src[k], 0); k += 1
    body = src[j:k - 1]
    assert counter in body, counter
    return body
rb = inner_body('uint32_t RebuildGGM(', 'nodes_used++')
cb = inner_body('uint32_t CountPublishedSeeds(', 'count++')
out = '''/* GENERATED by gen-walk-step.py from the real seedtree.c: the loop bodies below are verbatim copies. */
#include "seedtree.c"
#include <stdlib.h>
#ifndef SEEDTREE_WALK_STEP
#define SEEDTREE_WALK_STEP
int nondet_int(void); unsigned nondet_unsigned(void);
#define WL (LOG2(T))
static uint16_t P[WL + 2];                      /* start_node of each level in the walk */
static unsigned S[NUM_NODES_SEED_TREE + 1];     /* ghost suffix count of qualifying nodes */
static unsigned WEND;                           /* one past the last walked node */
/* ghost: the qualifying predicate, evaluated with the same father formula as the walks */
static void ghost_init(const unsigned char F[NUM_NODES_SEED_TREE]) {
    const uint16_t off[WL + 1] = TREE_OFFSETS; const uint16_t npl[WL + 1] = TREE_NODES_PER_LEVEL;
    P[1] = 1; for (int l = 1; l <= WL; l++) P[l + 1] = P[l] + npl[l];
    WEND = P[WL + 1];
    __CPROVER_assert(WEND <= NUM_NODES_SEED_TREE, "walk stays inside the node array");
    S[WEND] = 0;
    for (int l = WL; l >= 1; l--)
        for (int x = npl[l] - 1; x >= 0; x--) {
            unsigned cur = P[l] + x; unsigned fa = PARENT(cur) + (off[l - 1] >> 1);
            __CPROVER_assert(fa < NUM_NODES_SEED_TREE, "father index in range");
            S[cur] = S[cur + 1] + ((F[cur] == TO_PUBLISH) && (F[fa] == NOT_TO_PUBLISH));
        }
}
#define WALK_INV(level, nil, start_node, used) \\
    ((level) >= 1 && (level) <= WL && (nil) >= 0 && (nil) < npl[(level)] && (start_node) == P[(level)] && \\
     (used) >= 0 && (unsigned)(used) == S[1] - S[(start_node) + (nil)])

/* ONE iteration of RebuildGGM's walk, from an arbitrary invariant state, for an arbitrary flag tree and seed tree. */
void rebuild_step(unsigned char seed_tree[NUM_NODES_SEED_TREE * SEED_LENGTH_BYTES], const unsigned char flags_tree_to_publish[NUM_NODES_SEED_TREE],
                  const unsigned char *stored_seeds, const unsigned char salt[HASH_DIGEST_LENGTH]) {
    const uint32_t csprng_input_len = SALT_LENGTH_BYTES + SEED_LENGTH_BYTES;
    unsigned char csprng_input[SALT_LENGTH_BYTES + SEED_LENGTH_BYTES];
    SHAKE_STATE_STRUCT tree_csprng_state;
    const uint16_t off[LOG2(T)+1] = TREE_OFFSETS;
    const uint16_t npl[LOG2(T)+1] = TREE_NODES_PER_LEVEL;
    const uint16_t lpl[LOG2(T)+1] = TREE_LEAVES_PER_LEVEL;
    memcpy(csprng_input + SEED_LENGTH_BYTES, salt, SALT_LENGTH_BYTES);
    int level = nondet_int(), node_in_level = nondet_int(), start_node = nondet_int(), nodes_used = nondet_int();
    __CPROVER_assume(WALK_INV(level, node_in_level, start_node, nodes_used));
    {''' + rb + '''}
    node_in_level++;
    if (!(node_in_level < npl[level])) { start_node += npl[level]; level++; node_in_level = 0; }
    if (level <= WL) __CPROVER_assert(WALK_INV(level, node_in_level, start_node, nodes_used), "RebuildGGM walk invariant preserved");
    else __CPROVER_assert((unsigned)nodes_used == S[1], "RebuildGGM exit: exactly S[1] stored seeds consumed");
}

/* ONE iteration of CountPublishedSeeds' walk. */
void count_step(const unsigned char flags_tree_to_publish[NUM_NODES_SEED_TREE]) {
    const uint16_t off[LOG2(T)+1] = TREE_OFFSETS;
    const uint16_t npl[LOG2(T)+1] = TREE_NODES_PER_LEVEL;
    int level = nondet_int(), node_in_level = nondet_int(), start_node = nondet_int(); uint32_t count = nondet_unsigned();
    __CPROVER_assume(count <= NUM_NODES_SEED_TREE && WALK_INV(level, node_in_level, start_node, (int)count));
    {''' + cb + '''}
    node_in_level++;
    if (!(node_in_level < npl[level])) { start_node += npl[level]; level++; node_in_level = 0; }
    if (level <= WL) __CPROVER_assert(WALK_INV(level, node_in_level, start_node, (int)count), "CountPublishedSeeds walk invariant preserved");
    else __CPROVER_assert(count == S[1], "CountPublishedSeeds exit: count == S[1]");
}
#endif
'''
open(sys.argv[2], 'w').write(out)
print('gen-walk-step: extracted', len(rb), 'and', len(cb), 'bytes of loop body')
